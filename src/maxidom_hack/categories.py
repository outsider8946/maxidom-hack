def label(category: str) -> str:
    """Человекочитаемое имя типа товара для интерфейса."""
    return str(CATEGORIES.get(category, {}).get("label", category))


def query(category: str) -> str:
    """Текст поискового запроса для эмбеддинг-модели."""
    return str(CATEGORIES.get(category, {}).get("query", category))


def db_categories(category: str) -> list[str]:
    """Значения метаданного ``category`` в ChromaDB для типа товара."""
    return list(CATEGORIES.get(category, {}).get("db_categories", []))
