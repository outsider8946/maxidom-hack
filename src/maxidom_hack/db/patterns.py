    @classmethod
    def detect(cls, category_name: str) -> str | None:
        text = category_name.lower()
        matches: list[str] = []
        for label, patterns in (
            ("core", cls.CORE_PATTERNS),
            ("adjacent", cls.ADJACENT_PATTERNS),
            ("excluded", cls.EXCLUDED_PATTERNS),
        ):
            if any(p in text for p in patterns):
                matches.append(label)
        # ровно один класс — уверены; ноль или конфликт — отдаём LLM
        if len(matches) == 1:
            return matches[0]
        return None
