    MOISTURE_STRONG_NEGATIVE: list[str] = [
        "не влагостойк", "неводостойк", "не водостойк",
        "не предназначен для влажн",
        "не подходит для влажн",
        "не подходит для ванн",
        "для сухих помещений",
    ]

    # Опционально: маппинг категорий из БД → surface. Заполняйте под свои данные.
    # Категория сильнее текста, но требует ручной работы.
    CATEGORY_TO_SURFACE: dict[str, str] = {
        # "Ламинат": "напольное",
        # "Обои": "стеновое",
        # "Натяжные потолки": "потолочное",
        # "Кабель и провод": "электрика",
    }

    @classmethod
    def build_text(cls, item: dict[str, Any]) -> str:
        parts: list[str] = [item.get("name") or ""]
        if descr := item.get("marketing_description"):
            parts.append(descr)
        for f in item.get("characteristics") or []:
            name = (f.get("name") or "").lower()
            if "описание" in name:
                continue
            parts.append(f"{f.get('name', '')}: {f.get('value', '')}")
        for cat_name, cat_val in (item.get("categories") or {}).items():
            parts.append(f"{cat_name}: {cat_val}")
        return "\n".join(p for p in parts if p).lower()

    @classmethod
    def detect_surface(cls, text: str, categories: dict | None = None) -> str | None:
        # 1) Категория из БД — самый сильный сигнал (если маппинг заполнен)
        if categories:
            for cat_val in categories.values():
                if mapped := cls.CATEGORY_TO_SURFACE.get(cat_val):
                    return mapped

        # 2) Текстовый скоринг: побеждает категория с максимумом уникальных попаданий
        scores: dict[str, int] = {}
        for surface, keywords in cls.SURFACE_PATTERNS.items():
            hits = sum(1 for kw in keywords if kw in text)
            if hits:
                scores[surface] = hits
        if not scores:
            return None
        best = max(scores, key=scores.get)
        # Ничья → не уверены, отдаём модели
        if list(scores.values()).count(scores[best]) > 1:
            return None
        return best

    @classmethod
    def detect_moisture(cls, text: str) -> bool | None:
        has_pos = any(kw in text for kw in cls.MOISTURE_STRONG_POSITIVE)
        has_neg = any(kw in text for kw in cls.MOISTURE_STRONG_NEGATIVE)
        # «не влагостойкий» содержит и «влагостойк», и «не влагостойк» → двойное попадание.
        # При противоречии — None, пусть решает модель.
        if has_neg:
            return False if not has_pos else None
        return True if has_pos else None


